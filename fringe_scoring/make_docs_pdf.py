_BOLD_RE = re.compile(r"\*\*(.+?)\*\*")


def _draw_line(fig, x: float, y: float, line: str, size: float, color: str) -> None:
    """画一行，`**…**` 段加粗（标记本身不出现在纸面上）。

    matplotlib 单次 text() 只能一个字重，故按段测宽逐段落笔：每段画完取其
    display 宽度换算成 figure 坐标，作为下一段的起点。无加粗段时走单次调用。
    """
    parts: list[tuple[str, bool]] = []
    pos = 0
    for m in _BOLD_RE.finditer(line):
        if m.start() > pos:
            parts.append((line[pos:m.start()], False))
        parts.append((m.group(1), True))
        pos = m.end()
    if pos < len(line):
        parts.append((line[pos:], False))
    if len(parts) <= 1:
        fig.text(x, y, line, fontsize=size, color=color)
        return
    renderer = fig.canvas.get_renderer()
    fig_px = fig.get_figwidth() * fig.dpi
    cx = x
    for seg, bold in parts:
        if not seg:
            continue
        t = fig.text(cx, y, seg, fontsize=size, color=color,
                     fontweight="bold" if bold else "normal")
        cx += t.get_window_extent(renderer).width / fig_px


def render_pages(pdf: PdfPages, pages: list[list[tuple[str, str]]]) -> None:
    """把分页好的内容块渲染进 PDF：每页从上往下排版（内容手工分页，不自动断页）。

    公式行允许"中文名前缀 + $mathtext$"混排（mathtext 只解析 $ $ 内的部分）；
    vars 行同理，符号用 mathtext、释义用中文。
    """
    for blocks in pages:
        fig = plt.figure(figsize=PAGE)
        y = 0.94
        for kind, text in blocks:
            if kind == "space":
                y -= float(text)
                continue
            size, step = _STYLES[kind]
            if kind == "h1":
                fig.text(0.5, y, text, fontsize=size, ha="center", fontweight="bold")
                y -= step
            elif kind in ("h2", "h3"):
                fig.text(0.07, y, text, fontsize=size, fontweight="bold")
                y -= step
            elif kind == "formula":  # 公式：居中；中文标签放 $ $ 之外
                fig.text(0.5, y, text, fontsize=size, ha="center")
                y -= step
            elif kind == "vars":  # 变量清单：缩进一档，首行自动加"式中："
                fig.text(0.08, y, "式中：", fontsize=size, fontweight="bold")
                y -= step
                for line in text.split("\n"):
                    _draw_line(fig, 0.11, y, line, size, "black")
                    y -= step
            else:  # body / plain / note：逐行
                for line in text.split("\n"):
                    _draw_line(fig, 0.07, y, line, size,
                               "dimgray" if kind == "note" else "black")
                    y -= step
        pdf.savefig(fig)
        plt.close(fig)


