_VARS_GROUP_GAP = 0.018


def _draw_images(fig, y_top: float, items: list[tuple[str, float]],
                 h_frac: float, max_w: float) -> float:
    """在 y_top 之下绘制一组灰度图（items = [(ROOT相对路径, 中心 x)]），返回实际占高。

    宽度按图像纵横比从 h_frac 推算并封顶 max_w（超宽则整体等比缩小），
    imshow 固定 vmin/vmax 保持真实明暗（不做对比度拉伸）。
    """
    used = 0.0
    for rel, cx in items:
        img = plt.imread(str(ROOT / rel))
        ih, iw = img.shape[0], img.shape[1]
        w = h_frac * (PAGE[1] / PAGE[0]) * (iw / ih)
        h = h_frac
        if w > max_w:
            h, w = h * max_w / w, max_w
        ax = fig.add_axes([cx - w / 2, y_top - h, w, h])
        ax.imshow(img, cmap="gray", vmin=0.0, vmax=1.0, aspect="auto")
        ax.set_xticks([])
        ax.set_yticks([])
        for spine in ax.spines.values():
            spine.set_linewidth(0.5)
        used = max(used, h)
    return used


_BOLD_RE = re.compile(r"\*\*(.+?)\*\*")


def _draw_line(fig, x: float, y: float, line: str, size: float, color: str) -> None:
    """画一行，`**…**` 段加粗（标记本身不出现在纸面上）。

    matplotlib 单次 text() 只能一个字重，故按段测宽逐段落笔：每段画完取其
    display 宽度换算成 figure 坐标，作为下一段的起点。无加粗段时走单次调用。
    """
    parts: list[tuple[str, bool]] = []
    pos = 0
    for m in _BOLD_RE.finditer(line):
        if m.start() > pos:
            parts.append((line[pos:m.start()], False))
        parts.append((m.group(1), True))
        pos = m.end()
    if pos < len(line):
        parts.append((line[pos:], False))
    if len(parts) <= 1:
        fig.text(x, y, line, fontsize=size, color=color)
        return
    renderer = fig.canvas.get_renderer()
    fig_px = fig.get_figwidth() * fig.dpi
    cx = x
    for seg, bold in parts:
        if not seg:
            continue
        t = fig.text(cx, y, seg, fontsize=size, color=color,
                     fontweight="bold" if bold else "normal")
        cx += t.get_window_extent(renderer).width / fig_px


def render_page(blocks: list[tuple[str, str]]):
    """一页内容块 → matplotlib figure（供 PDF 与 PNG 校样共用）。"""
    fig = plt.figure(figsize=PAGE)
    y = 0.94
    for kind, text in blocks:
        if kind == "space":
            y -= float(text)
            continue
        if kind == "img":  # text = "ROOT相对路径::高度占比"，单图居中
            path, hs = text.rsplit("::", 1)
            y -= _draw_images(fig, y, [(path, 0.5)], float(hs), max_w=0.84) + 0.012
            continue
        if kind == "imgrow":  # "路径1::路径2::高度::题注1::题注2"，双图并排
            p1, p2, hs, c1, c2 = text.split("::")
            h_used = _draw_images(fig, y, [(p1, 0.28), (p2, 0.72)], float(hs), max_w=0.40)
            y -= h_used + 0.014
            for cx, cap in ((0.28, c1), (0.72, c2)):
                fig.text(cx, y, cap, fontsize=9, ha="center")
            y -= 0.020
            continue
        size, step = _STYLES[kind]
        if kind == "h1":
            fig.text(0.5, y, text, fontsize=size, ha="center", fontweight="bold")
            y -= step
        elif kind in ("sub", "cnote"):
            fig.text(0.5, y, text, fontsize=size, ha="center")
            y -= step
        elif kind in ("h2", "h3"):
            fig.text(0.07, y, text, fontsize=size, fontweight="bold")
            y -= step
        elif kind == "formula":
            fig.text(0.5, y, text, fontsize=size, ha="center")
            y -= step
        elif kind == "vars":  # "式中："与首行同行；组尾加组间距
            fig.text(0.085, y, "式中：", fontsize=size, fontweight="bold")
            for line in text.split("\n"):
                _draw_line(fig, 0.148, y, line, size, "black")
                y -= step
            y -= _VARS_GROUP_GAP
        elif kind == "tbl":
            for line in text.split("\n"):
                _draw_line(fig, 0.09, y, line, size, "black")
                y -= step
        else:  # body / note
            for line in text.split("\n"):
                _draw_line(fig, 0.07, y, line, size,
                           "dimgray" if kind == "note" else "black")
                y -= step
    return fig


def render_pages(pdf: PdfPages, pages: list[list[tuple[str, str]]]) -> None:
    """把分页好的内容块逐页渲染进 PDF（手工分页，不自动断页）。"""
    for blocks in pages:
        fig = render_page(blocks)
        pdf.savefig(fig)
        plt.close(fig)


